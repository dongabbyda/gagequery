def q(v):
    if v is None:
        return 'NULL'
    if isinstance(v, bool):
        return '1' if v else '0'
    if isinstance(v, (int,)):
        return str(v)
    if isinstance(v, float):
        return ('%.2f' % v)
    if isinstance(v, (dt.date, dt.datetime)):
        return "'" + (v.strftime('%Y-%m-%d %H:%M') if isinstance(v, dt.datetime) else v.isoformat()) + "'"
    return "'" + str(v).replace("'", "''") + "'"


def inserts(table, cols, rows):
    out = []
    for r in rows:
        out.append('INSERT INTO %s (%s) VALUES (%s);' % (table, ', '.join(cols), ', '.join(q(v) for v in r)))
    return '\n'.join(out)


def write(name, header, ddl, parts):
    sql = '-- ' + header + '\n-- Generated by gen_datasets.py with a fixed seed. Fictional data.\n\n' + ddl.strip() + '\n\n' + '\n\n'.join(parts) + '\n'
    open(os.path.join(OUT, name + '.sql'), 'w', encoding='utf-8').write(sql)


def day(start, end, R):
    span = (end - start).days
    return start + dt.timedelta(days=R.randint(0, span))


def person(R, used=None):
    while True:
        f, l = R.choice(FIRST), R.choice(LAST)
        if used is None or (f, l) not in used:
            if used is not None:
                used.add((f, l))
            return f, l


